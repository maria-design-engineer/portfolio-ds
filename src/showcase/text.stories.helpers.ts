// Неразрывный пробел после слов в одну-две буквы: предлог не остаётся в конце строки.
// Только для примеров витрины. На сайте текст приходит со страницы уже с неразрывными пробелами.
// Слово ищется по тому, что стоит перед ним, без захвата: короткие слова подряд — «и в двух» — получают пробел каждое.
const NBSP = String.fromCharCode(160)

export const nbsp = (text: string) => text.replace(/(?<=^|[\s(«])([A-Za-zА-Яа-яЁё]{1,2})\s/g, `$1${NBSP}`)
